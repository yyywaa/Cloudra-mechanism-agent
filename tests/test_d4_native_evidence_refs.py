"""D4: explicit ``properties.evidence_log`` references may point at native
xTB output or ``.xyz`` files, not only Gaussian/ORCA logs.

The species identity is still established by the geometry -> species check;
these tests pin the explicit-reference branch introduced by the D4 fairness
fix (native reference files were previously filtered out, which turned
otherwise evaluable deliveries into full ``no_evidence_penalty`` failures).
"""

import json
from pathlib import Path

from cloudra.benchmark.integrity import audit_integrity


def _write_graph(sandbox: Path, node: dict) -> None:
    (sandbox / "mechanism_graph.json").write_text(
        json.dumps({"nodes": [node], "edges": []}), encoding="utf-8"
    )


def _write_xyz(path: Path, atoms: list[tuple[str, float, float, float]]) -> None:
    lines = [str(len(atoms)), "generated by test"]
    lines.extend(f"{sym} {x:.6f} {y:.6f} {z:.6f}" for sym, x, y, z in atoms)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def test_explicit_xyz_reference_binds_species(tmp_path):
    _write_xyz(tmp_path / "min" / "N2.xyz", [("N", 0.0, 0.0, 0.0), ("N", 0.0, 0.0, 1.10)])
    _write_graph(
        tmp_path,
        {
            "id": "RC",
            "role": "reactant",
            "smiles": ["N#N"],
            "properties": {"evidence_log": "min/N2.xyz"},
        },
    )
    report = audit_integrity(tmp_path)
    assert report.graph_parseable
    assert len(report.node_bindings) == 1
    binding = report.node_bindings[0]
    assert binding.matched
    assert binding.quality > 0.0
    assert binding.bound_files == ["min/N2.xyz"]


def test_explicit_xyz_reference_rejects_wrong_species(tmp_path):
    _write_xyz(
        tmp_path / "wat.xyz",
        [("O", 0.0, 0.0, 0.0), ("H", 0.0, 0.0, 0.96), ("H", 0.93, 0.0, -0.24)],
    )
    _write_graph(
        tmp_path,
        {
            "id": "RC",
            "role": "reactant",
            "smiles": ["N#N"],
            "properties": {"evidence_log": "wat.xyz"},
        },
    )
    report = audit_integrity(tmp_path)
    assert report.node_bindings[0].matched is False
    assert report.node_bindings[0].bound_files == []


def test_explicit_reference_without_geometry_does_not_bind(tmp_path):
    (tmp_path / "notes.log").write_text("no geometry here\n", encoding="utf-8")
    _write_graph(
        tmp_path,
        {
            "id": "RC",
            "role": "reactant",
            "smiles": ["N#N"],
            "properties": {"evidence_log": "notes.log"},
        },
    )
    report = audit_integrity(tmp_path)
    assert report.node_bindings[0].matched is False


def test_explicit_reference_path_list_uses_first_usable(tmp_path):
    _write_xyz(tmp_path / "min" / "N2.xyz", [("N", 0.0, 0.0, 0.0), ("N", 0.0, 0.0, 1.10)])
    _write_graph(
        tmp_path,
        {
            "id": "RC",
            "role": "reactant",
            "smiles": ["N#N"],
            "properties": {"evidence_log": ["missing/N2.xyz", "min/N2.xyz"]},
        },
    )
    report = audit_integrity(tmp_path)
    binding = report.node_bindings[0]
    assert binding.matched
    assert binding.bound_files == ["min/N2.xyz"]
